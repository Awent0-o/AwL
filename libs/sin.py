def my_sin(x, terms=10) -> float:
    # 1. Переводимо кут у радіани, якщо він у градусах
    # (Цей рядок потрібен, лише якщо ви передаєте градуси)
    # x = x * 3.141592653589793 / 180 
    
    # 2. Зменшуємо аргумент до проміжку [-pi; pi], щоб покращить точність
    pi = 3.141592653589793
    x = x % (2 * pi)
    if x > pi:
        x -= 2 * pi
        
    # 3. Обчислення за допомогою ряду Тейлора
    sin_x = 0
    numerator = x       # Чисельник (x^n)
    denominator = 1     # Знаменник (n!)
    sign = 1            # Знак члена (+ або -)
    
    for i in range(1, 2 * terms, 2):
        sin_x += sign * (numerator / denominator)
        # Готуємо змінні для наступного кроку (наступного непарного числа)
        numerator *= x * x
        denominator *= (i + 1) * (i + 2)
        sign *= -1
        
    return sin_x
